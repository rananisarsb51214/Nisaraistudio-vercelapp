import { NextRequest, NextResponse } from 'next/server';
import { checkAndDeductCredits, refundQuotaOrCredit } from '@/lib/credits/credits-service';
import { createGeminiClient, parseGeminiError, resolveGeminiModel } from '@/lib/ai/gemini-error';

export const dynamic = 'force-dynamic';
export const runtime = 'nodejs';

interface IncomingHistoryMessage {
  role: 'user' | 'model';
  text: string;
}

interface IncomingMemoryNode {
  key?: string;
  value?: string;
  category?: string;
}

export async function POST(req: NextRequest) {
  let deductedFrom: 'daily_free' | 'paid_credits' | 'none' = 'none';
  let deductedCost = 0;
  let resolvedUserId = 'default_user';

  try {
    const body = await req.json().catch(() => ({}));
    const prompt = typeof body?.prompt === 'string' ? body.prompt.trim() : '';
    resolvedUserId =
      typeof body?.userId === 'string' && body.userId.trim()
        ? body.userId.trim()
        : 'default_user';

    const history: IncomingHistoryMessage[] = Array.isArray(body?.history)
      ? body.history
          .filter(
            (m: any) =>
              m &&
              typeof m.text === 'string' &&
              m.text.trim() &&
              (m.role === 'user' || m.role === 'model')
          )
          .slice(-20)
      : [];

    const memoryNodes: IncomingMemoryNode[] = Array.isArray(body?.memories)
      ? body.memories.slice(0, 20)
      : [];

    const agentPersona =
      typeof body?.systemInstruction === 'string' && body.systemInstruction.trim()
        ? body.systemInstruction.trim()
        : 'You are Nisar AI Agent, an intelligent assistant with persistent memory inside Nisar AI Studio. Answer clearly, recall saved memory facts accurately, and help automate coding, SEO, and marketing tasks.';

    if (!prompt) {
      return NextResponse.json(
        { success: false, error: 'Message prompt is required.' },
        { status: 400 }
      );
    }

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        {
          success: false,
          code: 'API_KEY_MISSING',
          error:
            'GEMINI_API_KEY is missing on the server. Add your Gemini API key in Settings > Secrets.',
        },
        { status: 500 }
      );
    }

    const deductRes = await checkAndDeductCredits(resolvedUserId, 1, 'ai-chatbot-memory');
    if (!deductRes.success) {
      return NextResponse.json(
        {
          success: false,
          code: deductRes.code || 'LIMIT_REACHED',
          error: deductRes.error || 'Daily credit limit reached.',
          quota: deductRes.quota,
        },
        { status: deductRes.code === 'LIMIT_REACHED' ? 429 : 500 }
      );
    }

    deductedFrom = deductRes.deductedFrom;
    deductedCost = deductRes.deductedCost;

    const memoryContextBlock =
      memoryNodes.length > 0
        ? `\n\n### Persistent Workspace Memory (Always remember & apply these saved facts):\n${memoryNodes
            .map(
              (m, idx) =>
                `${idx + 1}. [${m.category || 'general'}] ${m.key || 'fact'}: ${m.value || ''}`
            )
            .join('\n')}`
        : '';

    const fullSystemInstruction = `${agentPersona}${memoryContextBlock}`;

    const contents = [
      ...history.map((msg) => ({
        role: msg.role,
        parts: [{ text: msg.text }],
      })),
      {
        role: 'user' as const,
        parts: [{ text: prompt }],
      },
    ];

    const ai = createGeminiClient(apiKey);
    const modelToUse = resolveGeminiModel('gemini-4-hydrogen');

    const streamIterator = await ai.models.generateContentStream({
      model: modelToUse,
      contents,
      config: {
        systemInstruction: fullSystemInstruction,
      },
    });

    const encoder = new TextEncoder();
    const readable = new ReadableStream<Uint8Array>({
      async start(controller) {
        let emitted = false;
        try {
          for await (const chunk of streamIterator) {
            const text = chunk.text;
            if (text) {
              emitted = true;
              controller.enqueue(encoder.encode(text));
            }
          }
          if (!emitted) {
            controller.enqueue(encoder.encode('No response generated by Gemini.'));
          }
          controller.close();
        } catch (err) {
          if (deductedFrom !== 'none' && deductedCost > 0) {
            await refundQuotaOrCredit(resolvedUserId, deductedFrom, deductedCost, 'ai-chatbot-memory');
          }
          const parsed = parseGeminiError(err);
          controller.error(new Error(parsed.message));
        }
      },
    });

    return new Response(readable, {
      status: 200,
      headers: {
        'Content-Type': 'text/plain; charset=utf-8',
        'Cache-Control': 'no-cache, no-transform',
        'X-Model-Used': modelToUse,
      },
    });
  } catch (error: unknown) {
    if (deductedFrom !== 'none' && deductedCost > 0) {
      await refundQuotaOrCredit(resolvedUserId, deductedFrom, deductedCost, 'ai-chatbot-memory');
    }
    const parsed = parseGeminiError(error);
    return NextResponse.json(
      { success: false, code: parsed.code, error: parsed.message },
      { status: parsed.status }
    );
  }
}
